import { createContext, createElement, useCallback, useContext, useEffect, useState } from "react";

const KEY = "pressid-lang";
const LangCtx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(getLang);
  useEffect(() => {
    const onLang = (e) => {
      const v = e?.detail;
      if (v === "hi" || v === "en") setLangState(v);
    };
    const onStorage = (e) => {
      if (e.key === KEY && (e.newValue === "en" || e.newValue === "hi")) setLangState(e.newValue);
    };
    window.addEventListener("pressid-lang", onLang);
    window.addEventListener("storage", onStorage);
    return () => {
      window.removeEventListener("pressid-lang", onLang);
      window.removeEventListener("storage", onStorage);
    };
  }, []);
  useEffect(() => {
    try {
      document.documentElement.lang = lang === "hi" ? "hi" : "en";
    } catch { /* ignore */ }
  }, [lang]);
  const setLang = useCallback((l) => {
    const v = l === "hi" ? "hi" : "en";
    try { localStorage.setItem(KEY, v); } catch { /* ignore */ }
    setLangState(v);
    try { window.dispatchEvent(new CustomEvent("pressid-lang", { detail: v })); } catch { /* ignore */ }
  }, []);
  const toggle = useCallback(() => {
    setLangState((l) => {
      const v = l === "hi" ? "en" : "hi";
      try { localStorage.setItem(KEY, v); } catch { /* ignore */ }
      try { window.dispatchEvent(new CustomEvent("pressid-lang", { detail: v })); } catch { /* ignore */ }
      return v;
    });
  }, []);
  const tr = useCallback((key) => t(lang, key), [lang]);
  return createElement(LangCtx.Provider, { value: { lang, setLang, toggle, t: tr } }, children);
}
